export function getMegaHashtagsForCategory(
  category?: string,
  existingTags: string[] = []
): string[] {
  const catTags =
    category && DEPARTMENT_MEGA_HASHTAGS[category]
      ? DEPARTMENT_MEGA_HASHTAGS[category]
      : Object.values(DEPARTMENT_MEGA_HASHTAGS).flat();

  const generalTags = [
    '#شركة_همم_غيم',
    '#دعاية_واعلان_الرياض',
    '#مقاولات_عامة_الرياض',
    '#تنفيذ_مشاريع_السعودية',
    '#ضمان_معتمد_همم_غيم',
    '#Himam_Ghaim_Company',
    '#Riyadh_Signage_Contracting',
  ];

  return Array.from(
    new Set(
      [...existingTags, ...catTags, ...generalTags].map((t) =>
        t.startsWith('#') ? t : `#${t}`
      )
    )
  );
}

export function getHashtagTargetHref(tag: string, fallbackCategory?: string): string {
  const t = tag.toLowerCase();
  if (/حروف|احرف|لوح|توتم|اكريليك|ستانلس|sign|letter|totem/.test(t)) {
    return '/services/signage-3d-letters-cladding';
  }
  if (/كلادينج|تكسية|مقاولات|cladding|facade/.test(t)) {
    return '/services/general-contracting-cladding-glass';
  }
  if (/زجاج|سيكوريت|سبايدر|استركشر|glass|securit/.test(t)) {
    return '/services/structural-glass-facades-partitions';
  }
  if (/شيبورد|تلفزيون|ابواب_مخفية|أبواب_مخفية|بديل_الخشب|بديل_الرخام|chipboard|wpc|tv_wall/.test(t)) {
    return '/services/chipboard-wood-marble-cladding';
  }
  if (/جبس|اسمنت|سقف|اسقف|ديكور|تشطيب|gypsum|cement|interior/.test(t)) {
    return '/services/interior-design-decor-finishing';
  }
  if (/مظل|سواتر|ساتر|برجول|ليزر|حدادة|shade|pergola|screen/.test(t)) {
    return '/services/car-shades-pergolas-screens';
  }
  if (/تغليف|استيكر|سنفرة|بنر|جداري|wrap|sticker|film/.test(t)) {
    return '/services/stickers-vehicle-wrapping-murals';
  }
  if (/تسوير|سور|اسوار|هورينج|شينكو|hoarding|fence/.test(t)) {
    return '/services/project-hoarding-construction-fencing';
  }
  if (/معرض|معارض|بوث|جناح|كشك|اكشاك|ستاند|فعاليات|booth|kiosk/.test(t)) {
    return '/services/exhibition-booths-stands-events';
  }
  if (/اطفاء|حريق|رش|انذار|سلامة|دفاع|طوارئ|fire|sprinkler/.test(t)) {
    return '/services/security-cctv-fire-safety-systems';
  }
  if (/كامير|مراقب|امني|هيك|دهوا|cctv|camera|surveillance/.test(t)) {
    return '/services/cctv-security-surveillance-cameras';
  }
  if (fallbackCategory) {
    const map: Record<string, string> = {
      signage: '/services/signage-3d-letters-cladding',
      contracting: '/services/general-contracting-cladding-glass',
      glass: '/services/structural-glass-facades-partitions',
      interiors: '/services/interior-design-decor-finishing',
      chipboard: '/services/chipboard-wood-marble-cladding',
      shades: '/services/car-shades-pergolas-screens',
      stickers: '/services/stickers-vehicle-wrapping-murals',
      hoarding: '/services/project-hoarding-construction-fencing',
      exhibitions: '/services/exhibition-booths-stands-events',
      safety: '/services/security-cctv-fire-safety-systems',
      cctv: '/services/cctv-security-surveillance-cameras',
    };
    if (map[fallbackCategory]) return map[fallbackCategory];
  }
  return `/portfolio?q=${encodeURIComponent(tag.replace(/^#/, '').replace(/_/g, ' '))}`;
}
